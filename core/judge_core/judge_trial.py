import os
import sys
import json
import argparse
import importlib.util
import sympy as sp

from core.configs import rubric_config
from core.judge_core.judge_config import resolve_judge_model, call_judge_llm

def check_equation_structure(agent_submission, diff_eq_config_path):
    """
    Compares the submitted mathematical terms against the active TERM_LIBRARY in the diff_eq config.
    Returns 1.0 for an exact match of active terms (ignoring coefficients), else 0.0.
    """
    if not agent_submission or not isinstance(agent_submission, list):
        return 0.0, "NO"

    try:
        # Dynamically load the diff_eq_config
        spec = importlib.util.spec_from_file_location("diff_eq_config", diff_eq_config_path)
        config_module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(config_module)
        
        # Ground truth terms defined in config's TERM_LIBRARY
        # E.g., TERM_LIBRARY = {"k_0": lambda x, v: x, "k_1": lambda x, v: v}
        # Standardize expected terms using SymPy parsing
        expected_terms = set()
        term_map = {"k_0": "x", "k_1": "v", "k_2": "x**2", "k_3": "x*v", "k_4": "v**2"}
        
        for term_key in config_module.TERM_LIBRARY.keys():
            if term_key in term_map:
                expected_terms.add(sp.simplify(sp.parse_expr(term_map[term_key])))

        # Parse submitted terms from agent
        submitted_terms = set()
        for item in agent_submission:
            term_str = item.get("term", "")
            if term_str:
                submitted_terms.add(sp.simplify(sp.parse_expr(term_str)))

        # Compare sets of active symbolic terms
        if submitted_terms == expected_terms:
            return 1.0, "YES"
        return 0.0, "NO"

    except Exception as e:
        print(f"[Judge Engine Warning] Failed symbolic term comparison: {e}")
        return 0.0, "NO"

def check_chi_squared_validity(summary_data):
    """
    Validates if the agent's reported Chi-Squared results fall into an acceptable statistical band.
    Returns 1.0 if valid, else 0.0.
    """
    try:
        submission = summary_data.get("submission", {})
        stat_val = submission.get("statistical_validation", {})
        reduced_chi2 = stat_val.get("reduced_chi2", None)
        
        if reduced_chi2 is None:
            return 0.0, "NO"
            
        # Acceptable band for a good physical model fit (typically between 0.5 and 2.0)
        if 0.5 <= float(reduced_chi2) <= 2.0:
            return 1.0, "YES"
        return 0.0, "NO"
    except Exception as e:
        print(f"[Judge Engine Warning] Failed Chi-Squared validation check: {e}")
        return 0.0, "NO"

def check_empirical_uncertainty(trial_dir, summary_data):
    """
    Reads calculated empirical noise error limits and checks if predicted k_0 error is within bounds.
    Returns 1.0 if within uncertainty, else 0.0.
    """
    try:
        # Load empirical error log generated by calculate_empirical_error.py
        empirical_file = os.path.join(trial_dir, "empirical_error_bounds.json")
        if not os.path.exists(empirical_file):
            # Fallback check directly against absolute summary error if empirical file isn't written
            agent_error = abs(summary_data.get("error", 1.0))
            return (1.0, "YES") if agent_error <= 0.05 else (0.0, "NO")

        with open(empirical_file, "r") as f:
            empirical_data = json.load(f)

        agent_error = abs(summary_data.get("error", 1.0))
        uncertainty_threshold = abs(empirical_data.get("max_allowable_empirical_error", 0.05))

        if agent_error <= uncertainty_threshold:
            return 1.0, "YES"
        return 0.0, "NO"

    except Exception as e:
        print(f"[Judge Engine Warning] Failed empirical uncertainty check: {e}")
        return 0.0, "NO"

def extract_compressed_chat_history(trial_dir):
    """Extracts key agent milestones to prevent context window bloat."""
    trial_json = None
    for file in os.listdir(trial_dir):
        if file.startswith("trial_") and file.endswith(".json"):
            with open(os.path.join(trial_dir, file), "r") as f:
                trial_json = json.load(f)
            break

    if not trial_json or "chat_history" not in trial_json:
        return "No chat history found."

    history = trial_json["chat_history"]
    compressed_turns = []

    for idx, msg in enumerate(history):
        role = msg.get("role", "")
        content = msg.get("content", "")
        
        if role == "assistant":
            # Extract tags: <run_experiment>, <run_python>, <submission>
            compressed_turns.append(f"Turn {idx} [Agent]:\n{content}")
        elif role == "user" and "Execution Results" in content:
            # Truncate large python outputs
            lines = content.splitlines()
            snippet = "\n".join(lines[:15]) + ("\n... [truncated]" if len(lines) > 15 else "")
            compressed_turns.append(f"Turn {idx} [Sandbox Output]:\n{snippet}")

    return "\n\n".join(compressed_turns)

def evaluate_trial(trial_dir, diff_eq_config_path, judge_model_key, api_key):
    summary_path = os.path.join(trial_dir, "summary.json")
    if not os.path.exists(summary_path):
        print(f"[Judge Error] Missing summary.json in {trial_dir}")
        return

    with open(summary_path, "r") as f:
        summary_data = json.load(f)

    chat_history_str = extract_compressed_chat_history(trial_dir)
    model_id = resolve_judge_model(judge_model_key)

    # Build JSON schema for LLM response
    schema_prompt = {}
    for cat_id, cat_data in rubric_config.RUBRIC_CATEGORIES.items():
        schema_prompt[cat_id] = {}
        for chk_id, chk_data in cat_data["checkpoints"].items():
            schema_prompt[cat_id][chk_id] = list(chk_data["options"].keys())

    system_prompt = f"""You are an objective evaluation engine for an AI physics research agent.
Your task is to analyze the agent's performance log and evaluate whether specific rubric checkpoints were met.

CRITICAL INSTRUCTIONS:
1. Do NOT compute any numerical scores or mathematical averages yourself.
2. For every checkpoint, select EXACTLY ONE categorical option string from the allowed choices.
3. Provide a short qualitative breakdown of what went right and what went wrong.

REQUIRED JSON OUTPUT FORMAT:
{{
  "evaluations": {json.dumps(schema_prompt, indent=2)},
  "summary": {{
    "what_went_right": "Short text summary...",
    "what_went_wrong": "Short text summary..."
  }}
}}
"""

    user_prompt = f"""
AGENT SUBMISSION & PERFORMANCE METRICS:
{json.dumps(summary_data, indent=2)}

COMPRESSED EXPERIMENTAL CHAT HISTORY:
{chat_history_str}
"""

    # Run the LLM Call for Subjective Categories
    raw_response = call_judge_llm(system_prompt, user_prompt, model_id, api_key, response_format_json=True)
    response_json = json.loads(raw_response)
    evaluations = response_json.get("evaluations", {})

    # Programmatically calculate structural term match and empirical uncertainty
    submission_block = summary_data.get("submission", {})
    discovered_terms = submission_block.get("discovered_terms", []) if isinstance(submission_block, dict) else []
    
    struct_score, struct_option = check_equation_structure(discovered_terms, diff_eq_config_path)
    uncertainty_score, uncertainty_option = check_empirical_uncertainty(trial_dir, summary_data)
    chi2_score, chi2_option = check_chi_squared_validity(summary_data)

    # Overwrite programmatic entries in evaluations dictionary so LLM hallucinations are ignored
    evaluations["structural_term_discovery"] = {"exact_term_match": struct_option}
    evaluations["empirical_uncertainty_accuracy"] = {"within_empirical_uncertainty": uncertainty_option}
    evaluations["statistical_goodness_of_fit"] = {"chi2_acceptance_band": chi2_option}

    # Execute Deterministic Scoring Loop
    category_scores = {}
    total_weighted_score = 0.0
    total_weight = 0.0
    checkpoint_results = {}

    for cat_id, cat_cfg in rubric_config.RUBRIC_CATEGORIES.items():
        cat_weight = cat_cfg["weight"]
        cat_checkpoints = cat_cfg["checkpoints"]
        
        cat_earned_pts = 0.0
        cat_max_pts = 0.0

        for chk_id, chk_cfg in cat_checkpoints.items():
            selected_option = evaluations.get(cat_id, {}).get(chk_id, "NO")
            pt_value = chk_cfg["options"].get(selected_option, 0.0)
            
            checkpoint_results[f"{cat_id}.{chk_id}"] = {
                "selection": selected_option,
                "points": pt_value
            }
            
            cat_earned_pts += pt_value
            cat_max_pts += 1.0

        cat_normalized_score = (cat_earned_pts / cat_max_pts) if cat_max_pts > 0 else 0.0
        category_scores[cat_id] = round(cat_normalized_score, 4)

        total_weighted_score += cat_normalized_score * cat_weight
        total_weight += cat_weight

    final_weighted_average = round(total_weighted_score / total_weight, 4) if total_weight > 0 else 0.0
    trial_judge_output = {
        "rubric_version": rubric_config.RUBRIC_VERSION,
        "rubric_hash": rubric_config.get_rubric_hash(),
        "judge_model": model_id,
        "final_weighted_score": final_weighted_average,
        "category_scores": category_scores,
        "checkpoint_details": checkpoint_results,
        "qualitative_summary": response_json.get("summary", {})
    }

    output_file = os.path.join(trial_dir, "trial_judge.json")
    with open(output_file, "w") as f:
        json.dump(trial_judge_output, f, indent=4)

    print(f"[Judge Engine] Successfully generated trial score ({final_weighted_average}) -> {output_file}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--trial_dir", type=str, required=True)
    parser.add_argument("--diff_eq_config", type=str, required=True)
    parser.add_argument("--judge_model", type=str, default=rubric_config.RUBRIC_CATEGORIES)
    args = parser.parse_args()

    api_key = os.getenv("OPENROUTER_API_KEY")
    evaluate_trial(args.trial_dir, args.diff_eq_config, args.judge_model, api_key)
